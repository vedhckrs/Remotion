/**
 * Color grades in two flavours that always agree:
 *  - `css` + `washes`: CSS filters and blend-mode color washes. Work on any HTML tree, in Studio
 *    and in renders, no WebGL. Use <Graded> to apply to a whole scene.
 *  - `effects()`: @remotion/effects stack for canvas media (<Video>, <CanvasImage>). WebGL.
 *  - `lut`: name of a .cube generated by scripts/make-lut.mjs (public/luts/<name>.cube) for the
 *    exact same look through the lut() effect. See <LutVideo>.
 */
export type GradeName = 'none' | 'teal-orange' | 'warm-film' | 'cool-noir' | 'vibrant-pop' | 'bleach-bypass' | 'matte-fade' | 'neon-night';

export type Wash = {
  readonly color: string;
  readonly blend: React.CSSProperties['mixBlendMode'];
  readonly opacity: number;
  /** CSS gradient; defaults to a full-frame solid. */
  readonly gradient?: string;
};

export type Grade = {
  readonly label: string;
  readonly css: string;
  readonly washes: readonly Wash[];
  readonly effects: () => EffectDescriptor<unknown>[];
  readonly lut: string | null;
};

