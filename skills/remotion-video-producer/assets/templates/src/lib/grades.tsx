export const GRADE_NAMES = Object.keys(GRADES) as GradeName[];

/** Wraps any scene tree in a grade: CSS filter plus blend-mode washes on top. Works without WebGL. */
export const Graded: React.FC<{readonly name: GradeName; readonly strength?: number; readonly children: React.ReactNode}> = ({name, strength = 1, children}) => {
  const grade = GRADES[name];
  if (name === 'none' || strength <= 0) return <>{children}</>;
  return (
    <AbsoluteFill>
      <AbsoluteFill style={{filter: grade.css}}>{children}</AbsoluteFill>
      {grade.washes.map((wash, i) => (
        <AbsoluteFill key={i} style={{background: wash.gradient ?? wash.color, mixBlendMode: wash.blend, opacity: wash.opacity * strength, pointerEvents: 'none'}} />
      ))}
    </AbsoluteFill>
  );
};
